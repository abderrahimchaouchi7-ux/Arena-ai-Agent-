/**
 * Widens every leaf to `string` while preserving the exact nested shape, so
 * `fr` and `ar` are type-checked for key parity (and nothing else) without
 * being forced to repeat English wording.
 */
type Widen<T> = T extends string
  ? string
  : T extends readonly (infer U)[]
    ? Widen<U>[]
    : { [K in keyof T]: Widen<T[K]> };

export type TranslationKeys = Widen<typeof en>;
export default en;
